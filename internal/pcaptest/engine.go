package pcaptest

import (
	"fmt"
	"net/netip"
	"strconv"
	"strings"
	"time"
)

// side identifies one end of a hop: L is closer to the caller.
type side int

const (
	sideL side = 0
	sideR side = 1
)

// dlg is the dialog state of one signalling leg: Call-ID, tags, parties and
// CSeq counters. Direct and Proxy topologies share one dlg across hops, B2BUA
// uses one per hop.
type dlg struct {
	callID     string
	lTag, rTag string
	lName      string
	rName      string
	lURI, rURI string
	cseq       [2]int
	sess       [2]uint64
	ver        [2]int
}

// hop is one signalling link between two network elements.
type hop struct {
	l, r    netip.AddrPort // actual packet endpoints
	lat     time.Duration  // one way latency
	d       *dlg
	contact [2]string         // contact URI (no brackets) each side presents on this hop
	ua      [2]string         // User-Agent / Server value of each side
	via     [2]string         // Via sent-by each side uses
	adv     [2]netip.AddrPort // media address advertised in SDP by each side
	real    [2]netip.AddrPort // media address packets really use (differs behind NAT)
	sdpUser [2]string
	uriHost [2]string // host part of the request URI used when this side is the target
}

func (h *hop) ap(sd side) netip.AddrPort {
	if sd == sideL {
		return h.l
	}
	return h.r
}

// scn is one scenario in flight (a call, a registration, ...).
type scn struct {
	b      *Builder
	hops   []*hop
	topo   Topology
	tcp    bool
	midTag string // To tag generated by the proxy / SBC for its own responses
	proxy  netip.AddrPort
	domain string
	toUser string
	rr     string // Record-Route value (proxy topology)
	xcid   string // X-CID shared by both B2BUA legs
	nonce  string // digest nonce of the current challenge
	// emitAt holds the emission time of the request on each hop for the
	// most recent reqUpTo call.
	emitAt []time.Time

	proxyUA string

	compact         bool // drop optional headers
	coalesce, split bool // TCP quirks, see CallOptions
	splitCSeq       int
	pending         *pendingTCP
}

func (s *scn) trName() string {
	if s.tcp {
		return "TCP"
	}
	return "UDP"
}

// path returns the hop indices in the order a request travelling in the given
// direction visits them.
func (s *scn) path(fwd bool) []int {
	n := len(s.hops)
	p := make([]int, n)
	for i := range p {
		if fwd {
			p[i] = i
		} else {
			p[i] = n - 1 - i
		}
	}
	return p
}

func senderSide(fwd bool) side {
	if fwd {
		return sideL
	}
	return sideR
}

// txn is one SIP transaction across all hops of the scenario.
type txn struct {
	method  string
	fwd     bool
	cseq    []int
	branch  []string
	vias    [][]string // per hop index: Via stack of the request on that hop, top first
	body    []string   // per hop index
	extra   [][2]string
	first   [][2]string // extra headers on the first hop only
	est     bool        // To carries the remote tag
	toTag   []string    // explicit To tag per hop index (ACK to a failure response)
	initial bool        // request URI is built from the user part rather than the peer contact
	user    string      // request URI user for initial requests
	uri     string      // explicit request URI overriding everything (REGISTER, ...)
	route   bool        // add Route in proxy topology on the first hop
	contact bool        // send Contact
	ctype   string      // body content type (default application/sdp)
	accept  string
}

// newTxn creates a transaction. cseqFrom copies CSeq numbers (ACK for 2xx,
// CANCEL), sameBranch copies Via branches (CANCEL, ACK for failures).
func (s *scn) newTxn(method string, fwd bool, cseqFrom, sameBranch *txn) *txn {
	n := len(s.hops)
	x := &txn{method: method, fwd: fwd, cseq: make([]int, n), branch: make([]string, n),
		vias: make([][]string, n), body: make([]string, n), toTag: make([]string, n)}
	path := s.path(fwd)
	snd := senderSide(fwd)
	var prev []string
	for pos, hi := range path {
		h := s.hops[hi]
		switch {
		case cseqFrom != nil:
			x.cseq[hi] = cseqFrom.cseq[hi]
		case pos > 0 && h.d == s.hops[path[pos-1]].d:
			x.cseq[hi] = x.cseq[path[pos-1]]
		default:
			h.d.cseq[snd]++
			x.cseq[hi] = h.d.cseq[snd]
		}
		if sameBranch != nil {
			x.branch[hi] = sameBranch.branch[hi]
		} else {
			x.branch[hi] = s.b.newBranch()
		}
		via := fmt.Sprintf("SIP/2.0/%s %s;rport;branch=%s", s.trName(), h.via[snd], x.branch[hi])
		if s.topo == Proxy && pos > 0 {
			// the proxy annotates the Via it received before pushing its own
			prevHop := s.hops[path[pos-1]]
			stack := append([]string(nil), prev...)
			stack[0] = annotateVia(stack[0], prevHop.ap(snd), prevHop.via[snd])
			x.vias[hi] = append([]string{via}, stack...)
		} else {
			x.vias[hi] = []string{via}
		}
		prev = x.vias[hi]
	}
	return x
}

// annotateVia adds the rport value and, when the sent-by host differs from the
// packet source, a received parameter, as a server receiving the request does.
func annotateVia(via string, src netip.AddrPort, sentBy string) string {
	via = strings.Replace(via, ";rport;", ";rport="+strconv.Itoa(int(src.Port()))+";", 1)
	host := sentBy
	if i := strings.LastIndexByte(host, ':'); i >= 0 {
		host = host[:i]
	}
	host = strings.Trim(host, "[]")
	if host != src.Addr().String() {
		via = strings.Replace(via, ";branch=", ";received="+src.Addr().String()+";branch=", 1)
	}
	return via
}

func (s *scn) jitterLat(h *hop) time.Duration {
	return h.lat + time.Duration(s.b.rng.IntN(400))*time.Microsecond
}

func (s *scn) proc() time.Duration {
	return 300*time.Microsecond + time.Duration(s.b.rng.IntN(900))*time.Microsecond
}

func nameAddr(name, uri string) string {
	if name == "" {
		return "<" + uri + ">"
	}
	return fmt.Sprintf("%q <%s>", name, uri)
}

func withTag(to, tag string) string {
	if tag == "" || strings.Contains(to, ";tag=") {
		return to
	}
	return to + ";tag=" + tag
}

const allowList = "INVITE, ACK, CANCEL, OPTIONS, BYE, REFER, SUBSCRIBE, NOTIFY, INFO, MESSAGE"

// fromTo returns From and To of transaction x on hop hi (no response tag).
func (s *scn) fromTo(x *txn, hi int) (from, to string) {
	d := s.hops[hi].d
	l := nameAddr(d.lName, d.lURI)
	r := nameAddr(d.rName, d.rURI)
	if senderSide(x.fwd) == sideL {
		from = l + ";tag=" + d.lTag
		to = r
		switch {
		case x.est:
			to += ";tag=" + d.rTag
		case x.toTag[hi] != "":
			to += ";tag=" + x.toTag[hi]
		}
		return
	}
	return r + ";tag=" + d.rTag, l + ";tag=" + d.lTag
}

// buildReq builds the request of x as seen on the hop at path position pos.
func (s *scn) buildReq(x *txn, pos int) *msg {
	hi := s.path(x.fwd)[pos]
	h := s.hops[hi]
	d := h.d
	snd := senderSide(x.fwd)
	m := &msg{method: x.method, cseq: x.cseq[hi], branch: x.branch[hi]}
	uri := x.uri
	if uri == "" {
		if x.initial {
			uri = "sip:" + x.user + "@" + h.uriHost[1-snd]
		} else {
			uri = h.contact[1-snd]
		}
	}
	m.start = x.method + " " + uri + " SIP/2.0"
	for _, v := range x.vias[hi] {
		m.add("Via", v)
	}
	mf := 70
	if s.topo == Proxy {
		mf -= pos
	}
	m.add("Max-Forwards", strconv.Itoa(mf))
	if s.topo == Proxy && x.route && pos == 0 && !x.initial {
		m.add("Route", "<"+s.rr+">")
	}
	if s.topo == Proxy && x.initial && x.method == "INVITE" && pos > 0 {
		m.add("Record-Route", "<"+s.rr+">")
	}
	from, to := s.fromTo(x, hi)
	m.add("From", from)
	m.add("To", to)
	m.add("Call-ID", d.callID)
	m.add("CSeq", fmt.Sprintf("%d %s", x.cseq[hi], x.method))
	if s.xcid != "" && x.method == "INVITE" && x.initial {
		m.add("X-CID", s.xcid)
	}
	if x.contact && !(s.compact && x.method == "ACK") {
		m.add("Contact", "<"+h.contact[snd]+">")
	}
	for _, e := range x.extra {
		m.add(e[0], e[1])
	}
	if pos == 0 {
		for _, e := range x.first {
			m.add(e[0], e[1])
		}
	}
	switch x.method {
	case "INVITE", "OPTIONS", "REGISTER", "SUBSCRIBE", "MESSAGE":
		if !s.compact {
			m.add("Allow", allowList)
			m.add("Supported", "replaces, timer")
		}
	}
	if x.accept != "" {
		m.add("Accept", x.accept)
	}
	if ua := h.ua[snd]; ua != "" && (!s.compact || x.method == "INVITE" && x.initial) {
		m.add("User-Agent", ua)
	}
	if x.body[hi] != "" {
		ct := x.ctype
		if ct == "" {
			ct = "application/sdp"
		}
		m.add("Content-Type", ct)
		m.body = x.body[hi]
	}
	return m
}

// pendingTCP is a message held back so it can share a TCP segment with the next one.
type pendingTCP struct {
	h    *hop
	from side
	data []byte
}

func (s *scn) emit(h *hop, from side, m *msg, at time.Time) {
	data := m.bytes()
	if s.tcp && (s.coalesce || s.split) {
		if p := s.pending; p != nil {
			s.pending = nil
			if p.h == h && p.from == from {
				data = append(p.data, data...)
			} else {
				s.b.add(at, p.h.ap(p.from), p.h.ap(1-p.from), true, p.data)
			}
		} else if s.coalesce && m.code == 100 {
			s.pending = &pendingTCP{h, from, data}
			return
		}
		if s.split && m.method == "INVITE" && m.code == 0 && m.cseq == s.splitCSeq && len(data) > 80 {
			cut := strings.Index(string(data), "\r\nCall-ID:") + 9 // inside the header block
			s.b.add(at, h.ap(from), h.ap(1-from), true, data[:cut])
			s.b.add(at.Add(2*time.Millisecond), h.ap(from), h.ap(1-from), true, data[cut:])
			return
		}
	}
	s.b.add(at, h.ap(from), h.ap(1-from), s.tcp, data)
}

// flush emits a message still held for coalescing.
func (s *scn) flush(at time.Time) {
	if p := s.pending; p != nil {
		s.pending = nil
		s.b.add(at, p.h.ap(p.from), p.h.ap(1-p.from), true, p.data)
	}
}

// req emits the request of x on the hop at path position pos at time at and
// returns the arrival time at the receiving element.
func (s *scn) req(x *txn, pos int, at time.Time) time.Time {
	h := s.hops[s.path(x.fwd)[pos]]
	s.emit(h, senderSide(x.fwd), s.buildReq(x, pos), at)
	return at.Add(s.jitterLat(h))
}

// reqUpTo emits the request on path positions 0..last, each forwarded after a
// short processing delay. extra delays the first receiver's processing (the
// request was retransmitted meanwhile). It returns the arrival time at every
// position.
func (s *scn) reqUpTo(x *txn, last int, at time.Time, extra time.Duration) []time.Time {
	arr := make([]time.Time, last+1)
	s.emitAt = make([]time.Time, last+1)
	t := at
	for pos := 0; pos <= last; pos++ {
		s.emitAt[pos] = t
		arr[pos] = s.req(x, pos, t)
		if pos == 0 {
			arr[pos] = arr[pos].Add(extra)
		}
		t = arr[pos].Add(s.proc())
	}
	return arr
}

// respOpts shapes a response.
type respOpts struct {
	contact bool
	rr      bool
	body    []string // per hop index
	extra   [][2]string
	ctype   string
	hdrs    func(hi int, m *msg)
	gen     bool // response is generated by the proxy / SBC itself, not relayed
}

// tagDlg asks resp to use the dialog's remote tag of each hop.
const tagDlg = "\x00dlg"

// resp emits one response of x on the hop at path position pos. The response
// is sent by the receiving side of that hop. It returns the arrival time at
// the requester side.
func (s *scn) resp(x *txn, pos, code int, tag string, ro respOpts, at time.Time) time.Time {
	hi := s.path(x.fwd)[pos]
	h := s.hops[hi]
	d := h.d
	reqSnd := senderSide(x.fwd)
	rsp := 1 - reqSnd
	m := &msg{method: x.method, code: code, cseq: x.cseq[hi], branch: x.branch[hi]}
	m.start = fmt.Sprintf("SIP/2.0 %d %s", code, reasonPhrase(code))
	for i, v := range x.vias[hi] {
		if i == 0 {
			v = annotateVia(v, h.ap(reqSnd), h.via[reqSnd])
		}
		m.add("Via", v)
	}
	if ro.rr && s.topo == Proxy {
		m.add("Record-Route", "<"+s.rr+">")
	}
	from, to := s.fromTo(x, hi)
	if tag == tagDlg {
		if reqSnd == sideL {
			tag = d.rTag
		} else {
			tag = d.lTag
		}
	}
	m.add("From", from)
	m.add("To", withTag(to, tag))
	m.add("Call-ID", d.callID)
	m.add("CSeq", fmt.Sprintf("%d %s", x.cseq[hi], x.method))
	if ro.contact {
		m.add("Contact", "<"+h.contact[rsp]+">")
	}
	for _, e := range ro.extra {
		m.add(e[0], e[1])
	}
	if ro.hdrs != nil {
		ro.hdrs(hi, m)
	}
	if code >= 200 && (x.method == "INVITE" || x.method == "OPTIONS") && code < 300 && !s.compact {
		m.add("Allow", allowList)
		m.add("Supported", "replaces, timer")
	}
	srvUA := h.ua[rsp]
	if ro.gen && s.topo == Proxy {
		srvUA = s.proxyUA
	}
	if srvUA != "" && (!s.compact || x.method == "INVITE" && code == 200) {
		m.add("Server", srvUA)
	}
	if ro.body != nil && ro.body[hi] != "" {
		ct := ro.ctype
		if ct == "" {
			ct = "application/sdp"
		}
		m.add("Content-Type", ct)
		m.body = ro.body[hi]
	}
	s.emit(h, rsp, m, at)
	return at.Add(s.jitterLat(h))
}

// respDown emits the response on path positions from..lo (descending), each
// relayed after a processing delay, and returns the arrival time at position lo.
func (s *scn) respDown(x *txn, from, lo, code int, tag string, ro respOpts, at time.Time) time.Time {
	t := at
	for pos := from; pos >= lo; pos-- {
		arr := s.resp(x, pos, code, tag, ro, t)
		t = arr.Add(s.proc())
		if pos == lo {
			return arr
		}
	}
	return t
}

// ackFailure emits the hop by hop ACK for a non-2xx final response to the
// INVITE x on the hop at path position pos. tag is the To tag of the response.
func (s *scn) ackFailure(x *txn, pos int, tag string, at time.Time) {
	hi := s.path(x.fwd)[pos]
	a := *x
	a.method = "ACK"
	a.est = false
	a.initial = true
	a.contact = false
	a.extra = nil
	a.body = make([]string, len(x.body))
	a.toTag = make([]string, len(x.toTag))
	a.toTag[hi] = tag
	a.vias = append([][]string(nil), x.vias...)
	a.vias[hi] = x.vias[hi][:1]
	h := s.hops[hi]
	s.emit(h, senderSide(x.fwd), s.buildReq(&a, pos), at)
}

// failInvite sends the final failure response of the INVITE x generated at
// path position k and walks it back to the caller with the hop by hop ACKs.
// It returns the time the caller received it.
func (s *scn) failInvite(x *txn, k, code int, tag string, ro respOpts, at time.Time) time.Time {
	t := at
	var arr time.Time
	for pos := k; pos >= 0; pos-- {
		tg := tag
		hi := s.path(x.fwd)[pos]
		if tg == tagDlg {
			if senderSide(x.fwd) == sideL {
				tg = s.hops[hi].d.rTag
			} else {
				tg = s.hops[hi].d.lTag
			}
		}
		r := ro
		r.gen = ro.gen && pos == k
		arr = s.resp(x, pos, code, tg, r, t)
		s.ackFailure(x, pos, tg, arr.Add(s.proc()))
		t = arr.Add(s.proc())
	}
	return arr
}

// timerSchedule returns the offsets (from the first transmission) of the
// retransmissions of an INVITE (timer A: doubling from T1=500 ms, uncapped,
// until 64*T1) or, with capT2, of a non-INVITE request / 2xx response (capped
// at T2=4 s).
func timerSchedule(capT2 bool) []time.Duration {
	var out []time.Duration
	const t1 = 500 * time.Millisecond
	step := t1
	at := time.Duration(0)
	for {
		at += step
		if at >= 64*t1 {
			return out
		}
		out = append(out, at)
		step *= 2
		if capT2 && step > 8*t1 {
			step = 8 * t1
		}
	}
}
